# Buat program untuk menghitung luas persegi panjang
# Nama variabel ditambah 4 digit nim terakhir contoh: panjang_2020
# Program ini menggunakan fungsi input() untuk meminta penguna
# memasukkan nilai panjang dan lebar persegi panjang.
# Nilai yang dimasukkan akan dikorversi menjadi tipe data integer
panjang_2020 = input('Masukkan nilai panjang: ')
lebar_2020 = input('Masukkan nilai lebar: ')
luas_2020 = int(panjang_2020) * int(lebar_2020)
print("Luas =", luas_2020)